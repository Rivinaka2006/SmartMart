    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // Add Storage
        String Storage = jTextField1.getText();

        if (Storage.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a brand to add", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            try {
                MySQL2.executeIUD("INSERT INTO `storage` (`storage`) VALUES ('" + Storage + "')");
                loadStorage();
                jTextField1.setText("");
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // Delete Storage
        int row = jTable1.getSelectedRow();
        int selectedRowCount = jTable1.getSelectedRowCount();

        if (selectedRowCount == 0) {
            JOptionPane.showMessageDialog(this, "Select a storage variant to delete", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            String id = String.valueOf(jTable1.getValueAt(row, 0));
            int confirm = JOptionPane.showConfirmDialog(this,
                    "Deleting this storage variant will also remove its related products. Are you sure?",
                    "Warning",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.WARNING_MESSAGE);

            if (confirm == JOptionPane.YES_OPTION) {
                try {

                    MySQL2.executeIUD("DELETE FROM `smartmart`.`product` WHERE `storage_id`='" + id + "'");
                    MySQL2.executeIUD("DELETE FROM `storage` WHERE `id`='" + id + "'");

                    loadStorage();
                    jTextField1.setText("");
                } catch (Exception e) {
                    e.printStackTrace();
                }
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

