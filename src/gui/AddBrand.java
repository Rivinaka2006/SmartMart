    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
// Add Brand
        String Brand = jTextField1.getText().trim();

        if (Brand.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a brand to add", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (Brand.length() > 45) {
            JOptionPane.showMessageDialog(this, "Brand name is too long. Please enter a name with fewer than 45 characters.", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            try {

                ResultSet result = MySQL2.executeSearch("SELECT * FROM `brand` WHERE `name`='" + Brand + "'");
                if (result.next()) {
                    JOptionPane.showMessageDialog(this, "This brand already exists. Please enter a new brand.", "Warning", JOptionPane.WARNING_MESSAGE);
                } else {

                    MySQL2.executeIUD("INSERT INTO `brand` (`name`) VALUES ('" + Brand + "')");

                    loadBrand();
                    jTextField1.setText("");

                    JOptionPane.showMessageDialog(this, "Brand added successfully.", "Info", JOptionPane.INFORMATION_MESSAGE);
                }
            } catch (Exception e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "An error occurred while adding the brand.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }

    }//GEN-LAST:event_jButton1ActionPerformed

