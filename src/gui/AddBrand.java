    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
// Delete Brand
        int row = jTable1.getSelectedRow();
        int selectedRowCount = jTable1.getSelectedRowCount();

        if (selectedRowCount == 0) {
            JOptionPane.showMessageDialog(this, "Select a brand to delete", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            String id = String.valueOf(jTable1.getValueAt(row, 0));

            // Confirm deletion with the user
            int confirm = JOptionPane.showConfirmDialog(this,
                    "Deleting this brand will also remove its related products. Are you sure?",
                    "Warning",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.WARNING_MESSAGE);

            if (confirm == JOptionPane.YES_OPTION) {
                try {

                    ResultSet result = MySQL2.executeSearch("SELECT * FROM `brand` WHERE `id`='" + id + "'");
                    if (!result.next()) {
                        JOptionPane.showMessageDialog(this, "The selected brand does not exist.", "Error", JOptionPane.ERROR_MESSAGE);
                    } else {

                        MySQL2.executeIUD("DELETE FROM `smartmart`.`product` WHERE `brand_id`='" + id + "'");
                        MySQL2.executeIUD("DELETE FROM `brand` WHERE `id`='" + id + "'");

                        loadBrand();
                        jTextField1.setText("");

                        JOptionPane.showMessageDialog(this, "Brand and related products deleted successfully.", "Info", JOptionPane.INFORMATION_MESSAGE);
                    }
                } catch (Exception e) {
                    e.printStackTrace();
                    JOptionPane.showMessageDialog(this, "An error occurred while deleting the brand.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        }


    }//GEN-LAST:event_jButton2ActionPerformed
